"""Generate src/data/themes.js from spec.py + base.json (the preserved sky/light/far/rope/particles/name/facade structure).
usage: python3 tools/themes_new/gen.py"""
import json, os, re
from lib import *
import spec

BASE = json.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'base.json')))
PACK = {'e': 'env', 'a': 'acres', 'd': 'dng40', 'x': 'dng100'}

def sid(code):
    m = re.fullmatch(r'([eadx])(\d+)#(\d+)', code)
    assert m, code
    pack = PACK[m.group(1)]; num = m.group(2)
    keys = [k for k in BY_SHEET if k[0] == pack and k[1].split('_')[0] == num]
    assert len(keys) == 1, (code, keys)
    i = f'{pack}/{keys[0][1]}#{m.group(3)}'
    assert i in BY_ID, i
    return i

def tile(code):
    if code.startswith('s_'): ids = [t for t in TILES if t.startswith(code + '_')]
    else:
        _, n, v = code.split('_'); ids = [t for t in TILES if t.startswith(f'm_{n}_') and t.endswith('_' + v)]
    assert len(ids) == 1, (code, ids)
    return ids[0]

def tex(code):
    t = TILES[tile(code)]
    return {'src': t['src'], 'rect': t['rect']}

def stairs(code):
    st = TILES_DOC['stairs']; tid = tile(code)
    if tid not in st['order']: return None
    i = st['order'].index(tid); cw, ch = st['cell']
    return {'src': st['src'], 'rect': [(i % st['cols']) * cw, (i // st['cols']) * ch, cw, ch]}

def spr(code):
    s = BY_ID[sid(code)]
    return {'src': s['src'], 'rect': s['rect']}

def top_list(txt, frac):
    out = []
    for item in txt.split():
        pass
    for item in re.findall(r'\S+#\d+(?: ay=\d+)?', txt):
        code, *ov = item.split(' ')
        a = top_anchor(sid(code), frac)
        if ov: a[1] = int(ov[0][3:])
        out.append({**spr(code), 'anchor': a})
    return out

def props(txt):
    out = []
    for line in re.split(r'[|\n]', txt):
        p = line.split()
        if not p: continue
        code, h, layer, on, weight = p[:5]
        assert layer in ('back', 'mid', 'front') and on in ('ground', 'ledge', 'any', 'wall', 'hang'), line
        i = sid(code)
        a = hang_anchor(i) if on == 'hang' else wall_anchor(i) if on == 'wall' else ground_anchor(i)
        out.append({**spr(code), 'anchor': a, 'h': int(h), 'layer': layer, 'on': on, 'weight': int(weight),
                    'light': spec.LIGHTS[p[5]] if len(p) > 5 else None})
    return out

def facade(f):
    def conv(v):
        if isinstance(v, str) and v.startswith('env/textures/surfaces/'):
            k = os.path.basename(v)[:-4]
            if k in spec.FACADE_TILES: return tex(spec.FACADE_TILES[k])
        return v
    f = dict(f)
    for k in ('wall', 'roof', 'foundation', 'trim'): f[k] = [conv(v) for v in f[k]]
    if 'recipes' in f: f['recipes'] = [{**r, 'wall': conv(r['wall']), 'roof': conv(r['roof'])} for r in f['recipes']]
    return f

def js(v):
    if v is None: return 'null'
    if isinstance(v, bool): return 'true' if v else 'false'
    if isinstance(v, (int, float)): return repr(v)
    if isinstance(v, str): return json.dumps(v)
    if isinstance(v, list): return '[' + ', '.join(js(x) for x in v) + ']'
    return '{' + ', '.join(f'{k}: {js(x)}' for k, x in v.items()) + '}'

def lines(name, arr):
    if not arr: return f'    {name}: [],\n'
    return f'    {name}: [\n' + ''.join(f'      {js(x)},\n' for x in arr) + '    ],\n'

out = ['// GENERATED by tools/themes_new/gen.py from tools/themes_new/spec.py - edit the spec and re-run, not this file.\n',
       '// All src paths are relative to assets/. Platforms, props and textures come only from assets/env/new (side-view art).\n',
       '// TEX = {src, rect} (a 128px seamless tile). Anchors are px inside the rect: ground/ledge props = ground-contact point (sunk a few px);\n',
       '// on:"hang" = top-centre attach point; on:"wall" = centre; ledgeSprites/bridges = [x centre, y of the walkable top surface].\n\n',
       'export const THEMES = {\n']
for tid, b in BASE['THEMES'].items():
    s = spec.THEMES[tid]
    g = b['ground']; top, fill = s['ground']
    o = f'  {tid}: {{\n'
    o += f'    name: {js(b["name"])},\n    sky: {js(b["sky"])},\n    light: {js(b["light"])},\n'
    o += f'    ground: {js({"top": tex(top), "fill": tex(fill), "lip": g["lip"], "lipColor": g["lipColor"]})},\n'
    o += f'    ledge: {js({"tex": tex(s["ledge"][0]), "style": s["ledge"][1]})},\n'
    bw = s['backwall']
    o += f'    backwall: {js(None if bw is None else {"tex": tex(bw[0]), "tint": bw[1], "alpha": 1.0})},\n'
    o += f'    stairs: {js(stairs(fill))},\n'
    o += f'    far: {js(b["far"])},\n    rope: {js(b["rope"])},\n    particles: {js(b["particles"])},\n'
    o += lines('ledgeSprites', top_list(s['ledges'], 0.6))
    o += lines('bridges', top_list(s['bridges'], 0.85))
    o += lines('ladders', [spr(c) for c in s['ladders'].split()])
    o += lines('props', props(s['props']))
    drs = []
    for c in s['doors'].split():
        i = sid(c); drs.append({**spr(c), 'anchor': [BY_ID[i]['rect'][2] // 2, ground_anchor(i)[1]], 'h': 300})
    o += lines('doors', drs)
    if 'buildings' in b: o += f'    buildings: {js(b["buildings"])},\n'
    if 'facade' in b: o += f'    facade: {js(facade(b["facade"]))},\n'
    o += '  },\n'
    out.append(o)
out.append('};\n\n')
out.append(f'export const PORTAL_FX = {js(BASE["PORTAL_FX"])};\n')
out.append(f'export const CHESTS = {js(BASE["CHESTS"])};\n')
dst = os.path.join(ROOT, 'src/data/themes.js')
open(dst, 'w').write(''.join(out))
print('wrote', dst, sum(len(x) for x in out), 'bytes')
